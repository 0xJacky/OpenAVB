#!/usr/bin/env python3
"""Turn platform descriptions (*.json) into a table the boot ROM can carry.

The ROM is freestanding with no allocator and no filesystem, so nothing parses
JSON there: the platform description is data in the repository, and this turns
it into a static table compiled into the image.

    tools/gen_platform_profile.py [--platforms DIR] [--check]

--check reports whether the committed header is up to date instead of writing.

By default the descriptions under tests/platform/fixtures/platforms are used.
They carry only the fields this generator reads, so `--check` against them
proves the committed header is still what the generator produces.  An emulator
that keeps a fuller description of the same board can point `--platforms` (or
the OPENAVB_PLATFORMS_DIR environment variable) at its own directory.
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURE_PLATFORMS = os.path.join(
    ROOT, "tests", "platform", "fixtures", "platforms")
OUTPUT = os.path.join(
    ROOT, "include", "avp", "platform", "platform_profile.h")


def emit(platforms):
    out = []
    add = out.append
    add("/*")
    add(" * Generated by tools/gen_platform_profile.py from the platform")
    add(" * descriptions (tests/platform/fixtures/platforms by default).")
    add(" * Do not edit: change the JSON and regenerate.")
    add(" */")
    add("")
    add("#pragma once")
    add("")
    add("#include <stddef.h>")
    add("#include <stdint.h>")
    add("")
    add("typedef struct {")
    add("    uint32_t offset;")
    add("    uint32_t instruction;")
    add("} AVPImagePatch;")
    add("")
    # The image description used to be generated here as well -- the sizes,
    # both digests, the load address, the exception level and the patch table,
    # one AVPPlatformImage per build.  All of it is a property of one particular
    # payload, so a ROM carrying it could boot that payload and nothing else.
    # The ROM is told instead: the host works the description out of whatever
    # image is at hand and uploads it (tools/patchup.py) over the recovery
    # interface before the image itself goes up.  Only
    # AVPImagePatch, the shape the two sides agree on, is still declared here.

    # The dot pitch the presented display has, where it is not the glass's:
    # `machine.display_pitch`, matched by the ROM on disp0's own canvas size
    # and pitch, so a tree that says anything else is left alone.
    add("typedef struct {")
    add("    uint32_t canvas_width;")
    add("    uint32_t canvas_height;")
    add("    uint32_t panel_dot_pitch;")
    add("    uint32_t dot_pitch;")
    add("} AVPDisplayPitch;")
    add("")
    rows = []
    for platform in platforms:
        pitch = platform.get("machine", {}).get("display_pitch")
        if pitch:
            rows.append((platform.get("platform", "?"), pitch))
    add("static const AVPDisplayPitch avp_display_pitch[] "
        "__attribute__((unused)) = {")
    for name, pitch in rows:
        add("    /* %s: see machine.display_pitch.why */" % name)
        add("    { %d, %d, %d, %d }," % (pitch["canvas"][0], pitch["canvas"][1],
                                       pitch["panel_dot_pitch"],
                                       pitch["dot_pitch"]))
    if not rows:
        add("    { 0, 0, 0, 0 },")
    add("};")
    add("#define AVP_DISPLAY_PITCH_COUNT %d" % len(rows))
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--platforms",
        default=os.environ.get("OPENAVB_PLATFORMS_DIR") or FIXTURE_PLATFORMS,
        help="directory of platform *.json descriptions")
    arguments = parser.parse_args()
    platforms_dir = arguments.platforms

    names = sorted(name for name in os.listdir(platforms_dir)
                   if name.endswith(".json"))
    platforms = [json.load(open(os.path.join(platforms_dir, name)))
                 for name in names]
    generated = emit(platforms)

    if arguments.check:
        current = open(OUTPUT).read() if os.path.exists(OUTPUT) else ""
        if current != generated:
            print("%s is stale against %s; run tools/gen_platform_profile.py"
                  % (OUTPUT, platforms_dir),
                  file=sys.stderr)
            return 1
        print("%s is up to date with %s" % (OUTPUT, platforms_dir))
        return 0

    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    open(OUTPUT, "w").write(generated)
    print("wrote %s from %d platform(s)" % (OUTPUT, len(platforms)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
